"""Configuration Manager: ссылки на конфиги, резервные копии, откат, проверка и рендер.

Корневая причина «You're using an autogenerated config» в этапах 0-3: Hyprland
читает ~/.config/hypr/hyprland.conf, а ссылка на репозиторий создавалась отдельной
ручной командой. Нет ссылки, значит нет файла, значит Hyprland генерирует свой.
Поэтому здесь:
  1. ссылки создаёт установщик (с резервной копией существующего);
  2. запуск Preview идёт с явным `-c` на отрендеренный конфиг с абсолютными путями;
  3. «используется именно наш конфиг» проверяется у ЗАПУЩЕННОЙ сессии по отпечатку
     значений (hyprctl getoption), а не по `--verify-config`, который проверяет
     только синтаксис файла.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path

from .context import Ctx
from .keybinds import KeyManager, render_default, render_user
from .manifest import Component, DST_ROOTS
from .registry import atomic_write

PERF_PROFILES = {
    "quality": "# Профиль quality: значения из appearance.conf без изменений.\n",
    "balanced": ("# Профиль balanced: мягче блюр и тени.\n"
                 "decoration {\n    blur {\n        size = 6\n        passes = 2\n    }\n"
                 "    shadow {\n        range = 12\n    }\n}\n"),
    "lite": ("# Профиль lite: без блюра, теней и анимаций (слабые GPU, виртуалки, Live USB).\n"
             "decoration {\n    blur {\n        enabled = false\n    }\n"
             "    shadow {\n        enabled = false\n    }\n}\n"
             "animations {\n    enabled = false\n}\n"),
}

# Параметры, удалённые из Hyprland: советуем исправить, но решает пользователь.
DEPRECATED_OPTIONS = {
    "drop_shadow": "заменено блоком decoration { shadow { ... } }",
    "shadow_range": "заменено decoration:shadow:range",
    "new_is_master": "заменено master:new_status",
}


@dataclass
class LinkState:
    name: str
    src: Path
    dst: Path
    state: str  # ok | create | replace | dangling-wrong
    detail: str = ""

    def to_dict(self):
        return {"name": self.name, "src": str(self.src), "dst": str(self.dst),
                "state": self.state, "detail": self.detail}


class ConfigManager:
    def __init__(self, ctx: Ctx):
        self.ctx = ctx

    # ---------- ссылки ----------
    def resolve_dst(self, dst: str) -> Path:
        root, _, rest = dst.partition("/")
        return getattr(self.ctx, DST_ROOTS[root]) / rest

    def link_states(self, comp: Component) -> list[LinkState]:
        out = []
        for ln in comp.links:
            src = (self.ctx.repo / ln.src).resolve()
            dst = self.resolve_dst(ln.dst)
            if not src.exists():
                out.append(LinkState(ln.name, src, dst, "dangling-wrong", "в репозитории нет источника"))
            elif dst.is_symlink() and Path(os.readlink(dst)) == src:
                out.append(LinkState(ln.name, src, dst, "ok"))
            elif dst.is_symlink() or dst.exists():
                out.append(LinkState(ln.name, src, dst, "replace",
                                     "существующее будет перемещено в резервную копию"))
            else:
                out.append(LinkState(ln.name, src, dst, "create"))
        return out

    def _record(self, name: str) -> Path:
        # Формат записи совместим со scripts/link-configs.sh этапа 1: last-backup-<имя>.
        return self.ctx.backup_dir / f"last-backup-{name}"

    def apply_links(self, comp: Component, journal: list | None = None) -> list[LinkState]:
        results = []
        for st in self.link_states(comp):
            if st.state == "dangling-wrong":
                raise FileNotFoundError(f"{comp.id}: {st.detail}: {st.src}")
            if st.state == "ok":
                results.append(st)
                continue
            backup = "none"
            st.dst.parent.mkdir(parents=True, exist_ok=True)
            self.ctx.backup_dir.mkdir(parents=True, exist_ok=True)
            if st.dst.is_symlink() or st.dst.exists():
                backup = str(self.ctx.backup_dir / f"{st.name}.{time.strftime('%Y%m%d-%H%M%S')}")
                n = 0
                while Path(backup).exists() or Path(backup).is_symlink():
                    n += 1
                    backup = f"{backup.split('+')[0]}+{n}"
                shutil.move(str(st.dst), backup)
            atomic_write(self._record(st.name), backup + "\n")
            os.symlink(st.src, st.dst, target_is_directory=st.src.is_dir())
            st.state, st.detail = "ok", ("резервная копия: " + backup) if backup != "none" else "создано"
            if journal is not None:
                journal.append({"op": "link", "name": st.name, "dst": str(st.dst), "backup": backup})
            results.append(st)
        return results

    def rollback_link(self, name: str, dst: Path) -> str:
        """Возврат состояния до установки. Возвращает пояснение; ошибка: исключение."""
        rec = self._record(name)
        if not rec.exists():
            return f"[{name}] нет записи о резервной копии, пропущено"
        backup = rec.read_text().strip()
        if backup != "none" and not Path(backup).exists():
            raise FileNotFoundError(f"резервная копия не найдена: {backup}")
        if dst.is_symlink():
            dst.unlink()
        elif dst.exists():
            raise FileExistsError(f"{dst} существует и не ссылка: откат остановлен")
        if backup != "none":
            shutil.move(backup, str(dst))
        rec.unlink()
        return f"[{name}] " + ("восстановлено из " + backup if backup != "none" else "ссылка убрана")

    def unlink_component(self, comp: Component) -> list[str]:
        msgs = []
        for ln in comp.links:
            msgs.append(self.rollback_link(ln.name, self.resolve_dst(ln.dst)))
        return msgs

    # ---------- рендер ----------
    def _expand(self, text: str) -> str:
        c = self.ctx
        text = text.replace("~/.config/hypr", str(c.repo / "hypr"))
        text = text.replace("~/.local/state/hyprdesk", str(c.state_dir))
        # Вызовы CLI: в рендере всегда абсолютный путь, не зависящий от ~/.local/bin.
        text = text.replace("~/.local/bin/hyprown", str(c.repo / "bin" / "hyprown"))
        return text

    def render(self, mode: str, outdir: Path) -> Path:
        """Самодостаточный конфиг с абсолютными путями в outdir.

        mode: "desktop" (как в сессии) или "preview" (вложенное окно: Alt вместо Super,
        без переключения раскладки по Alt+Shift, чтобы не конфликтовать с KDE).
        """
        c = self.ctx
        outdir.mkdir(parents=True, exist_ok=True)
        hypr = c.repo / "hypr"
        self.ensure_performance_file()
        keys = KeyManager(c)
        keys.ensure_user_conf()
        main_lines = []
        for line in (hypr / "hyprland.conf").read_text(encoding="utf-8").splitlines():
            m = re.match(r"^(\s*)source\s*=\s*(.+?)\s*$", line)
            if m:
                target = Path(self._expand(m.group(2)).replace("~", str(c.home), 1)
                              if m.group(2).startswith("~") else m.group(2))
                if not target.is_absolute():
                    target = hypr / target
                copy = outdir / target.name
                text = target.read_text(encoding="utf-8") if target.exists() else ""
                if mode == "preview":
                    text = re.sub(r"(?m)^\$mainMod\s*=.*$", "$mainMod = ALT", text)
                    # Клавиши Preview берутся из реестра: там учтены комбинации, которые
                    # перехватывает KDE (Alt+Space), и переназначения пользователя.
                    if target.name == "keybinds.conf":
                        text = render_default(keys.binds, "preview")
                    elif target.name == "keybinds.user.conf":
                        text = render_user(keys.binds, keys.user(), "preview")
                copy.write_text(self._expand(text), encoding="utf-8")
                main_lines.append(f"{m.group(1)}source = {copy}")
                continue
            main_lines.append(self._expand(line))
        if mode == "preview":
            main_lines += ["", "# --- Preview: переопределения ---",
                           "input {", "    kb_options =", "}",
                           'exec-once = hyprctl notify 0 12000 "rgb(7aa2f7)" '
                           '"HyprlandOwn Preview. Alt+M: закрыть окно предпросмотра."']
        out = outdir / "hyprland.conf"
        out.write_text("\n".join(main_lines) + "\n", encoding="utf-8")
        return out

    def verify(self, hyprland_bin: str = "Hyprland") -> tuple[bool, str]:
        """Синтаксис отрендеренного конфига. НЕ доказывает, что сессия использует его."""
        if not self.ctx.runner.which(hyprland_bin):
            return False, "Hyprland не установлен: проверка пропущена"
        conf = self.render("desktop", self.ctx.state_dir / "rendered")
        res = self.ctx.runner.run([hyprland_bin, "--verify-config", "-c", str(conf)],
                                  mutates=False, timeout=30)
        text = (res.out + res.err).strip()
        bad = (not res.ok) or re.search(r"(?i)\berror\b", text)
        return (not bad), text or "ok"

    def lint(self) -> list[str]:
        out = []
        for f in sorted((self.ctx.repo / "hypr").glob("*.conf")):
            for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
                for opt, hint in DEPRECATED_OPTIONS.items():
                    if re.match(rf"^\s*{opt}\s*=", line):
                        out.append(f"{f.name}:{n}: {opt}: {hint}")
        return out

    # ---------- отпечаток: чей конфиг загружен в запущенном Hyprland ----------
    def expected_fingerprint(self) -> dict:
        text = (self.ctx.repo / "hypr" / "appearance.conf").read_text(encoding="utf-8")
        fp = {}
        for key, rx in (("decoration:rounding", r"(?m)^\s*rounding\s*=\s*(-?\d+)"),
                        ("general:gaps_out", r"(?m)^\s*gaps_out\s*=\s*(-?\d+)"),
                        ("general:gaps_in", r"(?m)^\s*gaps_in\s*=\s*(-?\d+)")):
            m = re.search(rx, text)
            if m:
                fp[key] = int(m.group(1))
        return fp

    def running_fingerprint(self, env: dict) -> tuple[dict, str]:
        """(значения запущенной сессии, ошибка). Стандартные значения Hyprland: rounding 0, gaps_out 20."""
        got = {}
        for key in self.expected_fingerprint():
            res = self.ctx.runner.run(["hyprctl", "-j", "getoption", key], mutates=False,
                                      timeout=10, env=env)
            if not res.ok:
                return {}, (res.err or res.out).strip() or f"hyprctl getoption {key} завершился с ошибкой"
            try:
                got[key] = json.loads(res.out).get("int")
            except ValueError:
                return {}, f"непонятный ответ hyprctl: {res.out[:80]}"
        return got, ""

    def uses_our_config(self, env: dict) -> tuple[bool | None, str]:
        """True/False или None, если проверить нельзя (сессия не найдена)."""
        want = self.expected_fingerprint()
        got, err = self.running_fingerprint(env)
        if err:
            return None, err
        diff = {k: (got.get(k), v) for k, v in want.items() if got.get(k) != v}
        if diff:
            parts = ", ".join(f"{k}: сейчас {a}, в нашем конфиге {b}" for k, (a, b) in diff.items())
            return False, f"Запущен НЕ конфиг проекта ({parts}). Вероятно, автогенерированный."
        return True, "значения запущенной сессии совпадают с hypr/appearance.conf"

    # ---------- производительность ----------
    def perf_file(self) -> Path:
        return self.ctx.state_dir / "performance.conf"

    def ensure_performance_file(self) -> None:
        f = self.perf_file()
        if not f.exists():
            atomic_write(f, PERF_PROFILES["quality"])

    def perf_profile(self) -> str:
        f = self.perf_file()
        if not f.exists():
            return "quality"
        text = f.read_text(encoding="utf-8")
        for name, body in PERF_PROFILES.items():
            if text == body:
                return name
        return "custom"

    def set_perf_profile(self, name: str) -> None:
        if name not in PERF_PROFILES:
            raise ValueError(f"профиль должен быть одним из {sorted(PERF_PROFILES)}")
        atomic_write(self.perf_file(), PERF_PROFILES[name])
